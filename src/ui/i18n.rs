pub fn strings(lang: &str) -> &'static Strings {
    if lang == "es" { &ES } else { &EN }
}

pub fn theme_name(lang: &str, id: &str) -> &'static str {
    if lang == "es" {
        match id {
            "system" => "Sistema",
            "dark" => "Oscuro",
            "light" => "Claro",
            "midnight" => "Medianoche",
            "ocean" => "Océano",
            "forest" => "Bosque",
            "grape" => "Uva",
            "sunset" => "Atardecer",
            "paper" => "Papel",
            "contrast" => "Alto contraste",
            _ => "Sistema",
        }
    } else {
        match id {
            "system" => "System",
            "dark" => "Dark",
            "light" => "Light",
            "midnight" => "Midnight",
            "ocean" => "Ocean",
            "forest" => "Forest",
            "grape" => "Grape",
            "sunset" => "Sunset",
            "paper" => "Paper",
            "contrast" => "High contrast",
            _ => "System",
        }
    }
}

